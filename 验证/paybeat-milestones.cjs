const assert=require('node:assert/strict');
const {JourneyTracker}=require('../桌面桌宠/journey.js');
const sample=(units,elapsed,extra={})=>({rewardUnits:units,elapsedMs:elapsed,day:'2026-10-22',currencyCode:'CNY',ready:true,billable:true,...extra});
const t=new JourneyTracker();
assert.equal(t.update(sample(0,0),0).reward,null);
for(let i=1;i<4;i++)assert.equal(t.update(sample(0,i*1000),i*1000).reward,null);
assert.equal(t.update(sample(1,4000),4000).reward.kind,'small');
assert.equal(t.update(sample(1,4000),4000).reward,null);
const first= t.update(sample(39,5000),5000);assert.equal(first.reward.kind,'small');
assert.equal(first.targetKind,'big');
assert.equal(t.update(sample(40,6000),6000).reward.kind,'big');
assert.equal(t.update(sample(199,7000),7000).targetKind,'flag');
assert.equal(t.update(sample(200,8000),8000).reward.kind,'flag');
assert.equal(t.update(sample(205,9000),9000).reward.kind,'small');
assert.equal(t.update(sample(205,9000,{billable:false}),10000).reward,null);
assert.equal(t.update(sample(205,9000,{billable:false}),20000).reward,null);
assert.equal(t.update(sample(205,9000),21000).reward,null);
assert.equal(t.update(sample(206,10000),22000).reward.kind,'small');
assert.equal(t.update(sample(500,300000),330000).reward,null,'no sleep catchup');
assert.equal(t.update(sample(501,301000),331000).reward.kind,'small');
assert.equal(t.update(sample(1,1000,{day:'2026-10-23'}),332000).reward,null);
assert.equal(t.update(sample(0,0,{day:'2026-10-23'}),333000).reward,null,'reset today');
assert.equal(t.update(sample(1,1000,{currencyCode:'USD'}),334000).reward,null,'currency change');
assert.equal(new JourneyTracker().update(sample(3000,3000000),0).reward,null,'first open');
assert.equal(t.update(sample(NaN,1000),335000),null);
console.log('PASS milestone boundaries, duplicates, pause/resume, sleep, reset, new day/currency and first entry');
